const assert = require('node:assert/strict');
const path = require('node:path');
const SwaggerParser = require('@apidevtools/swagger-parser');
(async () => {
 const api = await SwaggerParser.validate(path.join(__dirname,'../src/swagger.json'));
 assert.deepEqual(api.servers,[{url:'/v1',description:'API da mesma instalação'}]);
 assert.ok(api.components.securitySchemes.bearerAuth);
 for (const route of ['/relatorios/custos','/relatorios/custos/evolucao','/produto/{produto_id}/custo-base','/produto/{produto_id}/custos/historico','/lotes/alertas','/inventarios','/inventarios/{id}/aprovar','/usuario/login','/sessao','/dashboard','/catalogo/produtos','/catalogo/produtos/codigo','/compras/reposicao','/compras/pedidos','/relatorios/estoque','/relatorios/estoque.csv','/relatorios/consumo','/relatorios/compras','/acessos/usuarios','/cadastros/{tipo}']) assert.ok(api.paths[route],route);
 assert.ok(api.paths['/cadastros/{tipo}/opcoes']);
 assert.deepEqual(api.paths['/usuario/login'].post.security,[]);
 for(const path of ['/auth/configuracao','/auth/mfa','/auth/recuperar','/auth/redefinir','/seguranca','/seguranca/mfa/preparar','/seguranca/mfa/ativar','/seguranca/mfa/codigos','/seguranca/mfa/desativar','/seguranca/senha'])assert.ok(api.paths[path],path);
 assert.ok(api.paths['/usuario/login'].post.responses['429'].headers['Retry-After']);
 assert.equal(api.paths['/usuario/login'].post.responses['200'].content['application/json'].schema.oneOf.length,2);
 assert.ok(api.paths['/pedido'].post.responses['405']);
 assert.ok(!api.paths['/pedido'].post.responses['201']);
 assert.ok(api.paths['/movimentacao-estoque/{movimento_id}'].delete.responses['405']);
 const post=api.paths['/movimentacao-estoque'].post;
 assert.ok(post.parameters.some(p=>p.in==='header'&&p.name==='Idempotency-Key'&&p.required));
 assert.ok(api.paths['/relatorios/estoque.csv'].get.responses['200'].content['text/csv']);
 assert.ok(api.paths['/inventarios/{id}/aprovar'].post.parameters.some(p=>p.in==='header'&&p.name==='Idempotency-Key'&&p.required));
 assert.equal(api.components.schemas.MovimentoInput.properties.movimento_codigo_lido.type,'string');
 for(const tipo of ['consumo','compras'])assert.ok(api.paths['/relatorios/'+tipo+'.csv'].get.responses['200'].content['text/csv']);
 console.log(`PASS: OpenAPI válido, ${Object.keys(api.paths).length} caminhos; autenticação, idempotência, CSV e bloqueios legados conferidos.`);
})().catch(e=>{console.error(e);process.exitCode=1;});
