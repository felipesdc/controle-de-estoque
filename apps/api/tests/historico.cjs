const assert = require('node:assert/strict');
const pool = require('/app/dist/config/db').default;
const {listarHistorico, responsaveisHistorico} = require('/app/dist/services/historico');
const {movimentar,estornar} = require('/app/dist/services/estoque');
(async()=>{
  assert.equal(listarHistorico({}).total,0);
  await pool.query("INSERT INTO pi2_produtos (produto_descricao,produto_estado,produto_quantidade_estoque) VALUES ('Produto 100% _ especial',1,0),('Inativo',0,0)");
  for(let i=0;i<26;i++) movimentar({movimento_produto_id:1,movimento_tipo:'entrada',movimento_quantidade:1,movimento_observacao:`Teste ${i}`},1,`historico-chave-${String(i).padStart(3,'0')}`);
  const reversal=estornar(1,'Correção teste',1,'historico-estorno-001');
  await pool.query("UPDATE pi2_movimentos_estoque SET movimento_data='2026-10-27T02:59:59Z' WHERE movimento_id=1");
  await pool.query("UPDATE pi2_movimentos_estoque SET movimento_data='2026-10-27T03:00:00Z' WHERE movimento_id=2");
  await pool.query("INSERT INTO pi2_movimentos_estoque (movimento_produto_id,movimento_tipo,movimento_quantidade,movimento_data) VALUES (2,'entrada',1,'invalid'),(2,'entrada',1,'2018-12-01T02:00:00Z')");
  assert.equal(listarHistorico({}).total,29);
  assert.equal(listarHistorico({}).itens.length,10);
  assert.equal(listarHistorico({pagina:'2'}).itens[0].movimento_id,19);
  assert.equal(listarHistorico({pagina:'999'}).pagina,3);
  assert.equal(listarHistorico({tamanho:'25'}).itens.length,25);
  assert.equal(listarHistorico({produto:'2'}).total,2);
  assert.equal(listarHistorico({responsavel:'legado'}).total,2);
  assert.equal(listarHistorico({responsavel:'1'}).total,27);
  assert.equal(listarHistorico({tipo:'saida'}).itens[0].movimento_estorno_de,1);
  assert.equal(listarHistorico({q:'%',tamanho:'50'}).total,27);
  assert.equal(listarHistorico({q:'_'}).total,27);
  assert.equal(listarHistorico({q:"' OR 1=1 --"}).total,0);
  assert.equal(listarHistorico({inicio:'2026-10-26',fim:'2026-10-26'}).itens.some(m=>m.movimento_id===1),true);
  assert.equal(listarHistorico({inicio:'2026-10-27',fim:'2026-10-27',q:'1'}).itens.some(m=>m.movimento_id===1),false);
  assert.equal(listarHistorico({inicio:'2018-12-01',fim:'2018-12-01'}).total,1,'historical DST uses UTC-2');
  assert.equal(listarHistorico({inicio:'2018-11-30',fim:'2018-11-30'}).total,0);
  const original=listarHistorico({tamanho:'50'}).itens.find(m=>m.movimento_id===1);
  assert.equal(original.movimento_estornado_por,reversal.movimento_id);
  assert.deepEqual(responsaveisHistorico().map(r=>r.id),[1]);
  for(const params of [{pagina:'0'},{pagina:'1e2'},{tamanho:'100'},{produto:'1 OR 1=1'},{responsavel:[]},{q:['x']},{tipo:'estorno'},{inicio:'2026-02-30'},{inicio:'2026-10-28',fim:'2026-10-27'}]) assert.throws(()=>listarHistorico(params),e=>e.status===400);
  console.log('PASS: pagination, combined filters, literal search, São Paulo boundaries/DST, legacy history and reversal links.');
})().catch(e=>{console.error(e);process.exitCode=1});
